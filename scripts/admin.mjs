// Writes public/admin/ (Decap CMS). Until an OAuth proxy URL is configured, /admin shows a setup notice instead of a broken login.
import fs from 'node:fs'; import path from 'node:path';
import { INT, FLAGS } from './integrations.mjs';
const dir = path.resolve(import.meta.dirname, '../public/admin');
const q = s => JSON.stringify(String(s));
export function writeAdmin(cats) {
  fs.mkdirSync(dir, { recursive: true });
  const yml = `# Generated by scripts/admin.mjs — edit there.
backend:
  name: github
  repo: ${INT.cms.repo}
  branch: ${INT.cms.branch}
${INT.cms.oauthBaseUrl ? `  base_url: ${INT.cms.oauthBaseUrl}\n  auth_endpoint: auth\n` : ''}  open_authoring: true
  commit_messages:
    create: 'مقال جديد: {{slug}}'
    update: 'تحديث: {{slug}}'
    delete: 'حذف: {{slug}}'
    uploadMedia: 'وسائط: {{path}}'
    deleteMedia: 'حذف وسائط: {{path}}'
publish_mode: editorial_workflow
locale: ar
site_url: https://blog.alcode.ae
display_url: https://blog.alcode.ae
logo_url: https://blog.alcode.ae/brand/logo-ink.svg
media_folder: public/articles/uploads
public_folder: articles/uploads
slug: { encoding: unicode, clean_accents: false }
collections:
  - name: articles
    label: المقالات
    label_singular: مقال
    folder: content
    extension: md
    format: frontmatter
    create: true
    slug: '{{fields.slug}}'
    summary: '{{title}} — {{date}}'
    sortable_fields: [date, title, category]
    preview_path: 'article/{{filename}}/'
    fields:
      - { name: slug, label: 'المعرّف في الرابط (حروف لاتينية وشرطات)', widget: string, pattern: ['^[a-z0-9-]+$', 'حروف لاتينية صغيرة وأرقام وشرطات فقط'] }
      - { name: title, label: العنوان, widget: string }
      - { name: author, label: المؤلف, widget: string }
      - { name: book, label: 'الكتاب المصدر', widget: string, required: false }
      - { name: category, label: القسم, widget: select, options: [${cats.map(c => q(c.name)).join(', ')}] }
      - { name: date, label: 'تاريخ النشر', widget: datetime, format: 'YYYY-MM-DD', date_format: 'YYYY-MM-DD', time_format: false }
      - { name: cover, label: 'صورة الغلاف', widget: image, required: false }
      - { name: coverCaption, label: 'تعليق صورة الغلاف والمصدر', widget: string, required: false }
      - { name: excerpt, label: 'الملخّص', widget: text }
      - { name: tags, label: 'الوسوم (أماكن وموضوعات)', widget: list, required: false }
      - { name: era, label: 'الحقبة (للخط الزمني، كما وردت في النص)', widget: string, required: false }
      - { name: eraSort, label: 'ترتيب الحقبة (سنة رقمية)', widget: number, value_type: float, required: false }
      - { name: body, label: 'نص المقال', widget: markdown, modes: [raw], hint: 'ماركداون؛ الأشكال <figure> والاقتباسات تُكتب كما في المقالات الحالية' }
`;
  fs.writeFileSync(path.join(dir, 'config.yml'), yml);
  const head = `<!doctype html><html lang="ar" dir="rtl"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><meta name="robots" content="noindex,nofollow"><title>لوحة التحرير — مجلة الكود الرقمية</title><link rel="icon" href="/favicon.svg">`;
  const html = FLAGS.cms
    ? `${head}<style>/* RTL for the editor and preview text; Decap's chrome stays as shipped */ textarea,input,[data-slate-editor]{direction:rtl;text-align:right;font-family:"IBM Plex Sans Arabic",system-ui,sans-serif;font-size:17px;line-height:1.8}</style></head><body><script src="https://unpkg.com/decap-cms@3.17.1/dist/decap-cms.js"></script><script>CMS.registerPreviewStyle('/admin/preview.css');</script></body></html>`
    : `${head}<style>body{font-family:system-ui,sans-serif;background:#f6efe1;color:#1b1712;display:grid;place-items:center;min-height:100vh;margin:0;padding:1rem}main{max-width:34rem;line-height:1.9;font-size:18px}a{color:#8a5a12}</style></head><body><main><h1>لوحة التحرير قيد الإعداد</h1><p>سيُفعَّل تسجيل الدخول عبر GitHub هنا بعد ربط خادم المصادقة. إلى ذلك الحين يُنشر المقال بإضافته إلى مجلد <code>content</code> في المستودع.</p><p><a href="/">العودة إلى المجلة</a></p></main></body></html>`;
  fs.writeFileSync(path.join(dir, 'index.html'), html);
  fs.writeFileSync(path.join(dir, 'preview.css'), `body{direction:rtl;text-align:right;font-family:"IBM Plex Sans Arabic",system-ui,sans-serif;font-size:18px;line-height:1.9;background:#f6efe1;color:#1b1712;padding:1.5rem}h1,h2,h3{font-family:"Noto Kufi Arabic",sans-serif}img{max-width:100%;height:auto}figcaption{font-size:.85em;color:#5b4f3d}`);
}
